inline uint32_t readBigEndian(FILE *f)
{
    union
    {
        uint8_t b[4];
        uint32_t w;
    } swizzle;

    // Read data into swizzle union
    fread(&swizzle.w, 4, 1, f);

    // Swap endianess
    uint8_t tmp = swizzle.b[0];
    swizzle.b[0] = swizzle.b[3];
    swizzle.b[3] = tmp;
    
    tmp = swizzle.b[1];
    swizzle.b[1] = swizzle.b[2];
    swizzle.b[2] = tmp;
    return swizzle.w;
}

void loadImageData(const char *imageDatafilename, uint8_t *data)
{
    FILE *f = fopen(imageDatafilename, "rb");
    
    // Read header words
    const uint32_t magic = readBigEndian(f);
    const uint32_t numImages = readBigEndian(f);
    const uint32_t numRows = readBigEndian(f);
    const uint32_t numCols = readBigEndian(f);

    // Validate header words
    assert(magic == 0x803);
    assert(numRows == 28);
    assert(numCols == 28);
    assert(numImages == 10000);
    
    // Read data
    fread(data, 1, numImages * numRows * numCols, f);
    
    fclose(f);
}

